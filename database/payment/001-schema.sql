-- Payment institution database. Independent of the storefront database.
CREATE TABLE IF NOT EXISTS PAYMENT_INFO (
  ID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  HOLDER_NAME VARCHAR(200) NOT NULL,
  CARD_NUM VARCHAR(32) NOT NULL COMMENT 'Masked number only, e.g. ****4242',
  EXP_DATE VARCHAR(5) NOT NULL,
  CVV VARCHAR(4) NULL DEFAULT NULL COMMENT 'Compatibility with lab schema, never stored',
  CONFIRMATION_TOKEN VARCHAR(40) NOT NULL UNIQUE,
  CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CHECK (CVV IS NULL)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
