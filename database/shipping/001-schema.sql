-- Carrier database. Independent of the storefront and payment databases.
CREATE TABLE IF NOT EXISTS SHIPMENT (
  ID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  BUSINESS_ID VARCHAR(64) NOT NULL,
  RECIPIENT_NAME VARCHAR(200) NOT NULL,
  ADDRESS1 VARCHAR(200) NOT NULL,
  ADDRESS2 VARCHAR(200) NOT NULL DEFAULT '',
  CITY VARCHAR(200) NOT NULL,
  STATE VARCHAR(2) NOT NULL,
  COUNTRY VARCHAR(2) NOT NULL,
  POSTAL_CODE VARCHAR(10) NOT NULL,
  EMAIL VARCHAR(200) NOT NULL,
  PACKET_COUNT INT UNSIGNED NOT NULL,
  WEIGHT_POUNDS DECIMAL(6,2) NOT NULL,
  CONFIRMATION_TOKEN VARCHAR(16) NOT NULL UNIQUE,
  CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
