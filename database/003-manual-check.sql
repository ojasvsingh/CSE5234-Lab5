-- Uses demo data. ROLLBACK leaves no sample order behind (IDs may have gaps).
START TRANSACTION;
INSERT INTO PAYMENT_INFO (HOLDER_NAME, CARD_NUM, EXP_DATE)
VALUES ('Manual Demo', '****4242', '12/35');
SET @payment_id = LAST_INSERT_ID();
INSERT INTO SHIPPING_INFO (ADDRESS1, ADDRESS2, CITY, STATE, COUNTRY, POSTAL_CODE, EMAIL)
VALUES ('123 Trailhead Lane', '', 'Columbus', 'OH', 'US', '43210', 'manual@example.com');
SET @shipping_id = LAST_INSERT_ID();
INSERT INTO CUSTOMER_ORDER (CUSTOMER_NAME, CUSTOMER_EMAIL, SHIPPING_INFO_ID_FK, PAYMENT_INFO_ID_FK)
VALUES ('Manual Demo', 'manual@example.com', @shipping_id, @payment_id);
SET @order_id = LAST_INSERT_ID();
INSERT INTO CUSTOMER_ORDER_LINE_ITEM (ITEM_ID, ITEM_NUMBER, ITEM_NAME, QUANTITY, UNIT_PRICE, CUSTOMER_ORDER_ID_FK)
SELECT ID, ITEM_NUMBER, NAME, 2, UNIT_PRICE, @order_id FROM ITEM WHERE SLUG = 'ridge-daypack';
SELECT o.ID, o.STATUS, li.ITEM_NAME, li.QUANTITY, li.UNIT_PRICE,
       li.QUANTITY * li.UNIT_PRICE AS LINE_TOTAL, s.COUNTRY, p.CARD_NUM, p.CVV
FROM CUSTOMER_ORDER o
JOIN CUSTOMER_ORDER_LINE_ITEM li ON li.CUSTOMER_ORDER_ID_FK = o.ID
JOIN SHIPPING_INFO s ON s.ID = o.SHIPPING_INFO_ID_FK
JOIN PAYMENT_INFO p ON p.ID = o.PAYMENT_INFO_ID_FK
WHERE o.ID = @order_id;
ROLLBACK;
