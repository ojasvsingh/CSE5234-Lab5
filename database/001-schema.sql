-- MySQL 8.4 / Amazon RDS for MySQL. Safe to run again; never drops data.
CREATE TABLE IF NOT EXISTS ITEM (
  ID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  ITEM_NUMBER INT UNSIGNED NOT NULL UNIQUE,
  SLUG VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL UNIQUE,
  NAME VARCHAR(255) NOT NULL,
  DESCRIPTION VARCHAR(255) NOT NULL,
  AVAILABLE_QUANTITY INT UNSIGNED NOT NULL,
  UNIT_PRICE DECIMAL(10,2) NOT NULL CHECK (UNIT_PRICE >= 0),
  CATEGORY VARCHAR(100) NOT NULL,
  IMAGE VARCHAR(255) NOT NULL,
  COLOR VARCHAR(100) NOT NULL,
  TAG VARCHAR(100) NOT NULL,
  FEATURED BOOLEAN NOT NULL DEFAULT FALSE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS PAYMENT_INFO (
  ID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  HOLDER_NAME VARCHAR(200) NOT NULL,
  CARD_NUM VARCHAR(32) NOT NULL COMMENT 'Masked number only, e.g. ****4242',
  EXP_DATE VARCHAR(5) NOT NULL,
  CVV VARCHAR(4) NULL DEFAULT NULL COMMENT 'Compatibility with lab schema, never stored',
  CHECK (CVV IS NULL)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS SHIPPING_INFO (
  ID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  ADDRESS1 VARCHAR(200) NOT NULL,
  ADDRESS2 VARCHAR(200) NOT NULL DEFAULT '',
  CITY VARCHAR(200) NOT NULL,
  STATE VARCHAR(2) NOT NULL,
  COUNTRY VARCHAR(2) NOT NULL,
  POSTAL_CODE VARCHAR(10) NOT NULL,
  EMAIL VARCHAR(200) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS CUSTOMER_ORDER (
  ID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  CUSTOMER_NAME VARCHAR(200) NOT NULL,
  CUSTOMER_EMAIL VARCHAR(200) NOT NULL,
  SHIPPING_INFO_ID_FK INT UNSIGNED NOT NULL,
  PAYMENT_INFO_ID_FK INT UNSIGNED NOT NULL,
  STATUS VARCHAR(255) NOT NULL DEFAULT 'New',
  CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (SHIPPING_INFO_ID_FK) REFERENCES SHIPPING_INFO(ID),
  FOREIGN KEY (PAYMENT_INFO_ID_FK) REFERENCES PAYMENT_INFO(ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS CUSTOMER_ORDER_LINE_ITEM (
  ID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  ITEM_ID INT UNSIGNED NOT NULL,
  ITEM_NUMBER INT UNSIGNED NOT NULL,
  ITEM_NAME VARCHAR(255) NOT NULL,
  QUANTITY INT UNSIGNED NOT NULL CHECK (QUANTITY BETWEEN 1 AND 99),
  UNIT_PRICE DECIMAL(10,2) NOT NULL CHECK (UNIT_PRICE >= 0),
  CUSTOMER_ORDER_ID_FK INT UNSIGNED NOT NULL,
  FOREIGN KEY (ITEM_ID) REFERENCES ITEM(ID),
  FOREIGN KEY (CUSTOMER_ORDER_ID_FK) REFERENCES CUSTOMER_ORDER(ID),
  UNIQUE KEY one_line_per_item (CUSTOMER_ORDER_ID_FK, ITEM_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
