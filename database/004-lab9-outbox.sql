-- Saved in the order transaction. Never include payment fields.
CREATE TABLE IF NOT EXISTS SHIPMENT_OUTBOX (
  ID BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  ORDER_ID INT UNSIGNED NOT NULL UNIQUE,
  EVENT_ID VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL UNIQUE,
  DETAIL JSON NOT NULL,
  CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  NEXT_ATTEMPT_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PUBLISHED_AT TIMESTAMP NULL,
  ATTEMPTS INT UNSIGNED NOT NULL DEFAULT 0,
  LAST_ERROR_CODE VARCHAR(80) NULL,
  FOREIGN KEY (ORDER_ID) REFERENCES CUSTOMER_ORDER(ID),
  INDEX ready_events (PUBLISHED_AT, NEXT_ATTEMPT_AT, ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
